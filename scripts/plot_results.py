#!/usr/bin/env python3
"""Plots and summary tables from the Verilog simulations.

Reads results/loop_log.csv, results/fault_tmr0.csv, results/fault_tmr1.csv.
Writes results/loop_response.png, loop_load_step_zoom.png, fault_injection.png,
results/loop_summary.md, results/fault_summary.md.
"""
import csv, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
VREF = 5.0
BAND = 0.050   # settling band +/- 50 mV (1 %)

EVENTS = [  # (time us, label)
    (0, "Start-up, 28 V, 3 A"),
    (1500, "Load 3 A to 0.3 A"),
    (2500, "Load 0.3 A to 3 A"),
    (3500, "Bus 28 V to 22 V"),
    (4500, "Bus 22 V to 36 V"),
    (5500, "Bus 36 V to 28 V"),
]


def load(path):
    with open(path) as f:
        rows = list(csv.DictReader(f))
    def f(v):
        try:
            return float(v)
        except ValueError:      # 'x' before the first reset edge
            return float("nan")
    return {k: np.array([f(r[k]) for r in rows]) for k in rows[0].keys()}


def loop_plots(d):
    t, vo, il, duty = d["t_us"] / 1000.0, d["vo"], d["il"], d["duty"]
    fig, ax = plt.subplots(3, 1, figsize=(10, 8), sharex=True)
    ax[0].plot(t, vo, lw=0.8)
    ax[0].axhline(VREF, color="k", lw=0.5, ls=":")
    ax[0].set_ylabel("Vout (V)")
    ax[1].plot(t, il, lw=0.8, color="tab:orange")
    ax[1].set_ylabel("Inductor current (A)")
    ax[2].plot(t, duty, lw=0.8, color="tab:green")
    ax[2].set_ylabel("Duty (counts of 500)")
    ax[2].set_xlabel("Time (ms)")
    for a in ax:
        a.grid(alpha=0.3)
        for te, lab in EVENTS[1:]:
            a.axvline(te / 1000.0, color="r", lw=0.6, ls="--")
    for te, lab in EVENTS[1:]:
        ax[0].text(te / 1000.0 + 0.03, 6.4, lab, rotation=90, va="top", fontsize=7, color="r")
    ax[0].set_ylim(0, 7)
    ax[0].set_title("Closed loop: RTL PID controller driving the buck model")
    fig.tight_layout()
    fig.savefig(os.path.join(RES, "loop_response.png"), dpi=130)
    plt.close(fig)

    m = (d["t_us"] >= 1400) & (d["t_us"] <= 1900)
    fig, ax = plt.subplots(2, 1, figsize=(8, 5), sharex=True)
    ax[0].plot(d["t_us"][m], vo[m], lw=0.9)
    ax[0].axhline(VREF, color="k", lw=0.5, ls=":")
    ax[0].axhspan(VREF - BAND, VREF + BAND, color="g", alpha=0.12, label="+/-50 mV band")
    ax[0].set_ylabel("Vout (V)")
    ax[0].legend()
    ax[1].plot(d["t_us"][m], il[m], lw=0.9, color="tab:orange")
    ax[1].set_ylabel("IL (A)")
    ax[1].set_xlabel("Time (us)")
    ax[0].set_title("Load step 3 A to 0.3 A at 1500 us")
    for a in ax:
        a.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(RES, "loop_load_step_zoom.png"), dpi=130)
    plt.close(fig)


def loop_table(d):
    t, vo, il = d["t_us"], d["vo"], d["il"]
    lines = ["# Closed-loop results (auto-generated by scripts/plot_results.py)\n",
             "| Event | Peak deviation (mV) | Direction | Settling to +/-50 mV (us) | Peak IL (A) |",
             "|---|---|---|---|---|"]
    ends = [e[0] for e in EVENTS[1:]] + [6500]
    for (te, lab), tend in zip(EVENTS, ends):
        m = (t >= te) & (t < tend)
        dev = vo[m] - VREF
        k = int(np.argmax(np.abs(dev)))
        out = np.where(np.abs(dev) > BAND)[0]
        settle = (t[m][out.max()] - te) if len(out) else 0.0
        if lab.startswith("Start-up"):
            peak = f"{max(0.0, dev.max())*1000:.0f}"
            direction = "overshoot"
        else:
            peak = f"{abs(dev[k])*1000:.0f}"
            direction = "overshoot" if dev[k] > 0 else "undershoot"
        lines.append(f"| {lab} | {peak} | {direction} | {settle:.0f} | {il[m].max():.2f} |")
    ss = (t >= 6000) & (t < 6500)
    lines.append(f"\nSteady state (28 V, 3 A): mean Vout = {vo[ss].mean():.4f} V, "
                 f"ripple = {(vo[ss].max()-vo[ss].min())*1000:.1f} mV pk-pk.\n")
    open(os.path.join(RES, "loop_summary.md"), "w").write("\n".join(lines))


def fault_plots():
    r = {n: load(os.path.join(RES, f"fault_tmr{n}.csv")) for n in (0, 1)}
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.2), gridspec_kw={"width_ratios": [2, 1]})
    for n, c, lab in ((0, "tab:red", "No TMR"), (1, "tab:green", "TMR + voter + scrub")):
        pk = np.sort(np.maximum(r[n]["peak_mV"], 1.0))
        ax[0].plot(np.arange(1, len(pk) + 1), pk, ".", color=c, label=lab, ms=4)
    ax[0].axhline(100, color="k", ls="--", lw=0.8)
    ax[0].text(2, 115, "100 mV (2 %) limit", fontsize=8)
    ax[0].set_yscale("log")
    ax[0].set_xlabel("Injected upset (sorted by severity)")
    ax[0].set_ylabel("Peak Vout error after upset (mV)")
    ax[0].set_title("Single-bit upsets in controller state")
    ax[0].grid(alpha=0.3, which="both")
    ax[0].legend()
    bad = [int((r[n]["peak_mV"] > 100).sum()) for n in (0, 1)]
    ax[1].bar(["No TMR", "TMR"], bad, color=["tab:red", "tab:green"])
    for i, b in enumerate(bad):
        ax[1].text(i, b + 1, f"{b}/{len(r[0]['peak_mV'])}", ha="center")
    ax[1].set_ylabel("Upsets causing > 100 mV error")
    ax[1].grid(alpha=0.3, axis="y")
    fig.tight_layout()
    fig.savefig(os.path.join(RES, "fault_injection.png"), dpi=130)
    plt.close(fig)

    lines = ["# Fault injection results (auto-generated by scripts/plot_results.py)\n",
             "Single bit flip in one state copy at a random time; Vout observed for 300 us.\n",
             "| Metric | No TMR | TMR |", "|---|---|---|"]
    def stat(n):
        pk, tl = r[n]["peak_mV"], r[n]["tail_mV"]
        return dict(n=len(pk), bad=int((pk > 100).sum()), bad5=int((pk > 250).sum()),
                    nrec=int((tl > 50).sum()), mx=pk.max(), med=np.median(pk))
    s0, s1 = stat(0), stat(1)
    rows = [("Upsets injected", s0["n"], s1["n"]),
            ("Upsets with peak error > 100 mV (2 %)", s0["bad"], s1["bad"]),
            ("Upsets with peak error > 250 mV (5 %)", s0["bad5"], s1["bad5"]),
            ("Not recovered to +/-50 mV within 250 us", s0["nrec"], s1["nrec"]),
            ("Worst peak error (mV)", f"{s0['mx']:.0f}", f"{s1['mx']:.0f}"),
            ("Median peak error (mV)", f"{s0['med']:.0f}", f"{s1['med']:.0f}")]
    for a, b, c in rows:
        lines.append(f"| {a} | {b} | {c} |")
    bits = {n: r[n]["bit"] for n in (0, 1)}
    lines += ["", "## Breakdown by register (no TMR)\n", "| Register | Bits | Upsets | Caused > 100 mV |", "|---|---|---|---|"]
    for name, lo, hi in (("duty", 0, 10), ("e_prev", 10, 26), ("integrator", 26, 58)):
        m = (bits[0] >= lo) & (bits[0] < hi)
        lines.append(f"| {name} | {hi-lo} | {int(m.sum())} | {int(((r[0]['peak_mV'] > 100) & m).sum())} |")
    lines.append("\nWith TMR, the voter output masks the flipped copy; the mismatch flag is raised "
                 f"in {int(r[1]['detected'].sum())}/{s1['n']} cases (telemetry for ground).")
    open(os.path.join(RES, "fault_summary.md"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    d = load(os.path.join(RES, "loop_log.csv"))
    loop_plots(d)
    loop_table(d)
    fault_plots()
    print(open(os.path.join(RES, "loop_summary.md")).read())
    print(open(os.path.join(RES, "fault_summary.md")).read())
