#!/usr/bin/env python3
"""Compare the controller with and without Vin feedforward and soft start.

Reads results/ablation_{base,ff,ss,both}.csv (written by `make ablate`), writes
results/ablation_summary.md and results/ablation.png.
The 'base' run is the iteration 2 controller (identical waveform to the published log).
"""
import os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from plot_results import load, event_metrics, RES, VREF, BAND

RUNS = [("base", "Iteration 2 (neither)"), ("ff", "Vin feedforward only"),
        ("ss", "Soft start only"), ("both", "Feedforward + soft start")]


def main():
    data = {k: load(os.path.join(RES, f"ablation_{k}.csv")) for k, _ in RUNS}
    mets = {k: event_metrics(data[k]) for k, _ in RUNS}
    labels = [m[0] for m in mets["base"]]
    lines = ["# Ablation: feedforward and soft start (auto-generated by scripts/ablation.py)\n",
             "Peak deviation in mV / settling to +/-50 mV in us / peak inductor current in A.\n",
             "| Event | " + " | ".join(n for _, n in RUNS) + " |",
             "|---|" + "---|" * len(RUNS)]
    for i, lab in enumerate(labels):
        cells = [f"{mets[k][i][1]:.0f} / {mets[k][i][3]:.0f} / {mets[k][i][4]:.1f}" for k, _ in RUNS]
        lines.append(f"| {lab} | " + " | ".join(cells) + " |")
    lines.append("")

    # Same 200-upset sequence (70-bit state, seed 12345) on both controllers.
    # Upsets are injected back to back. Without TMR some upsets are still recovering when
    # the next one lands, which inflates that next peak. "Clean starts" keeps only upsets
    # whose predecessor had recovered to within 50 mV by the end of its window.
    lines += ["## Bit-flip fault injection, same 200 upsets on both controllers\n",
              "| Controller | Mode | Upsets > 100 mV | Upsets > 250 mV | Not recovered in 250 us | Worst peak (mV) | > 100 mV, clean starts only |",
              "|---|---|---|---|---|---|---|"]
    for tag, name in (("base", "Iteration 2"), ("", "Feedforward + soft start")):
        for n, mode in ((0, "no TMR"), (1, "TMR")):
            f = os.path.join(RES, f"fault_{tag + '_' if tag else ''}tmr{n}.csv")
            r = load(f)
            pk, tl = r["peak_mV"], r["tail_mV"]
            clean = [i for i in range(len(pk)) if i == 0 or tl[i - 1] <= 50]
            lines.append(f"| {name} | {mode} | {int((pk > 100).sum())} / {len(pk)} | {int((pk > 250).sum())} / {len(pk)} "
                         f"| {int((tl > 50).sum())} / {len(pk)} | {pk.max():.0f} "
                         f"| {sum(pk[i] > 100 for i in clean)} / {len(clean)} |")
    lines.append("")
    open(os.path.join(RES, "ablation_summary.md"), "w").write("\n".join(lines))
    print("\n".join(lines))

    fig, ax = plt.subplots(2, 2, figsize=(11, 6.5))
    cols = {"base": "tab:red", "ff": "tab:orange", "ss": "tab:blue", "both": "tab:green"}
    for k, n in RUNS:
        d = data[k]
        t = d["t_us"]
        m = t <= 1600
        ax[0, 0].plot(t[m], d["vo"][m], lw=0.9, color=cols[k], label=n)
        ax[1, 0].plot(t[m], d["il"][m], lw=0.9, color=cols[k])
        m = (t >= 4400) & (t <= 5000)
        ax[0, 1].plot(t[m] - 4500, d["vo"][m], lw=0.9, color=cols[k])
        ax[1, 1].plot(t[m] - 4500, d["il"][m], lw=0.9, color=cols[k])
    ax[0, 0].set_title("Start-up, 28 V, 3 A load")
    ax[0, 1].set_title("Bus step 22 V to 36 V at t = 0")
    ax[0, 0].set_ylabel("Vout (V)"); ax[1, 0].set_ylabel("Inductor current (A)")
    ax[1, 0].set_xlabel("Time (us)"); ax[1, 1].set_xlabel("Time since step (us)")
    for a in (ax[0, 0], ax[0, 1]):
        a.axhline(VREF, color="k", lw=0.5, ls=":")
    ax[0, 1].axhspan(VREF - 0.25, VREF + 0.25, color="g", alpha=0.10, label="250 mV target")
    ax[0, 0].legend(fontsize=7, loc="lower right")
    ax[0, 1].legend(fontsize=7, loc="lower right")
    for a in ax.flat:
        a.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(RES, "ablation.png"), dpi=130)
    print("wrote results/ablation.png")


if __name__ == "__main__":
    main()
